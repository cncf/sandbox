const fs = require('fs');

/**
 * Extract the first JSON object from raw Copilot CLI output.
 * The model is instructed to emit bare JSON, but this tolerates
 * markdown fences or stray prose around the object.
 * @param {string} raw - Raw stdout captured from the Copilot CLI
 * @returns {Object|null} Parsed verdict object, or null if unparseable
 */
function extractVerdict(raw) {
  const start = raw.indexOf('{');
  const end = raw.lastIndexOf('}');
  if (start === -1 || end === -1 || end <= start) {
    return null;
  }
  try {
    return JSON.parse(raw.slice(start, end + 1));
  } catch (error) {
    console.error(`❌ Failed to parse Copilot verdict JSON: ${error.message}`);
    return null;
  }
}

/**
 * Build the review comment body posted on the application issue.
 * @param {Object} verdict - Parsed verdict object from the Copilot review
 * @returns {string} Markdown comment body
 */
function buildCommentBody(verdict) {
  const lines = [
    '## 🤖 Automated Sandbox Application Pre-Review',
    '',
    '> [!NOTE]',
    '> This is an automated first-pass review generated by GitHub Copilot against the',
    '> [Sandbox acceptance criteria](https://github.com/cncf/sandbox#before-you-apply-common-reasons-applications-are-closed)',
    '> and the [CNCF TOC Principles](https://github.com/cncf/toc/blob/main/PRINCIPLES.md).',
    '> It is advisory only — the CNCF TOC makes all final decisions.',
    ''
  ];

  const violations = Array.isArray(verdict.violations) ? verdict.violations : [];
  if (violations.length > 0) {
    lines.push('### ❌ Clear violations detected', '');
    for (const v of violations) {
      lines.push(`- **${v.criterion || 'Violation'}**`);
      if (v.evidence) {
        lines.push(`  - Evidence: ${v.evidence}`);
      }
      if (v.guideline) {
        lines.push(`  - Guideline: ${v.guideline}`);
      }
    }
    lines.push(
      '',
      'The `Postponed` label has been applied automatically. Please review the',
      '[Postponed guidance](https://github.com/cncf/sandbox#postponed) for how to',
      'address these items and return for review. If you believe this assessment',
      'is incorrect, please leave a comment — CNCF staff and the TOC will take a look.',
      ''
    );
  }

  if (verdict.summary) {
    lines.push('### Assessment summary', '', verdict.summary, '');
  }

  const concerns = Array.isArray(verdict.concerns) ? verdict.concerns : [];
  if (concerns.length > 0) {
    lines.push('### ⚠️ Items for TOC verification (non-blocking)', '');
    for (const concern of concerns) {
      lines.push(`- ${concern}`);
    }
    lines.push('');
  }

  return lines.join('\n');
}

/**
 * Read the Copilot verdict file, then comment on (and, for clear
 * violations, label) the application issue.
 * @param {Object} github - GitHub API client (from actions/github-script)
 * @param {Object} context - GitHub Actions context
 * @param {string} verdictPath - Path to the file containing raw Copilot output
 */
async function applyVerdict(github, context, verdictPath) {
  const issueNumber = context.payload.issue.number;

  let raw;
  try {
    raw = fs.readFileSync(verdictPath, 'utf8');
  } catch (error) {
    console.error(`❌ Could not read verdict file at ${verdictPath}: ${error.message}`);
    return;
  }

  const verdict = extractVerdict(raw);
  if (!verdict || !verdict.verdict) {
    console.error('❌ Copilot output did not contain a usable verdict. Skipping — no labels or comments applied.');
    console.error(`Raw output (first 1000 chars): ${raw.slice(0, 1000)}`);
    return;
  }

  const isViolation = verdict.verdict === 'violation'
    && Array.isArray(verdict.violations)
    && verdict.violations.length > 0;

  console.log(`📋 Copilot verdict for issue #${issueNumber}: ${isViolation ? 'violation' : 'pass'}`);

  if (isViolation) {
    console.log('🏷️  Applying "Postponed" label...');
    await github.rest.issues.addLabels({
      owner: context.repo.owner,
      repo: context.repo.repo,
      issue_number: issueNumber,
      labels: ['Postponed']
    });
  }

  console.log('💬 Posting review comment...');
  await github.rest.issues.createComment({
    owner: context.repo.owner,
    repo: context.repo.repo,
    issue_number: issueNumber,
    body: buildCommentBody(verdict)
  });

  console.log(`✅ Automated pre-review complete for issue #${issueNumber}`);
}

module.exports = { applyVerdict, extractVerdict, buildCommentBody };
